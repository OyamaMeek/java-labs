package com.happanetwork.study.chapter2;

public class work2_1_20261008141530 {
    public static void main(String[] args) {
        // 设置圆的半径为 8。
        double r=8;
        // 声明用于保存圆面积的变量。
        double area;
        // 根据公式 S = πr² 计算面积，π 取近似值 3.14。
        area=r*r*3.14;
        // 将计算得到的圆面积输出到控制台。
        System.out.println(area);
    }
}
